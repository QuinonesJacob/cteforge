"""Import checks and the definition state rule (DESIGN §7, §8) against a real DuckDB."""

from pathlib import Path

from cteforge.domain.codec import AnnotationFile
from cteforge.domain.dialects import Dialect
from cteforge.domain.issues import IssueCode, Severity
from cteforge.domain.models import Annotation, DefinitionState
from cteforge.domain.variables import Role, VariableType
from cteforge.files.definitions import load_definition
from cteforge.services.import_query import import_query
from cteforge.services.render_definition import render_definition
from cteforge.warehouse.base import QueryResult

D = Dialect.DUCKDB
EXAMPLES = Path(__file__).resolve().parents[2] / "examples"


class Spy:
    """Wraps a warehouse, counting calls; optionally changes the second result."""

    def __init__(self, inner, *, dialect=D, tamper=False, truncate=False):
        self.inner, self.dialect, self.tamper, self.truncate = inner, dialect, tamper, truncate
        self.calls: list[str] = []

    def column_types(self, table):
        self.calls.append("column_types")
        return self.inner.column_types(table)

    def explain(self, sql):
        self.calls.append("explain")
        self.inner.explain(sql)

    def run(self, sql, limit):
        self.calls.append("run")
        result = self.inner.run(sql, limit)
        if self.tamper and self.calls.count("run") == 2:
            return QueryResult(columns=result.columns, rows=result.rows[:-1], truncated=False)
        return result.model_copy(update={"truncated": self.truncate})

    def close(self):
        pass


def _codes(outcome):
    return [(i.code, i.severity) for i in outcome.issues]


def test_without_warehouse_stays_draft_with_checks_incomplete(sample_sql, sample_annotations):
    outcome = import_query(sample_sql, D, sample_annotations)
    assert outcome.definition.state is DefinitionState.DRAFT
    assert outcome.results_match is None
    assert (IssueCode.CHECKS_INCOMPLETE, Severity.WARNING) in _codes(outcome)
    assert (IssueCode.TYPE_UNKNOWN, Severity.WARNING) in _codes(outcome)


def test_warehouse_of_another_dialect_runs_nothing(sample_sql, sample_annotations, warehouse):
    spy = Spy(warehouse, dialect=Dialect.SNOWFLAKE)
    outcome = import_query(sample_sql, D, sample_annotations, spy)
    assert spy.calls == []
    assert (IssueCode.DIALECT_MISMATCH, Severity.ERROR) in _codes(outcome)
    assert outcome.definition.state is DefinitionState.DRAFT
    assert outcome.results_match is None


def test_different_results_are_an_error(sample_sql, sample_annotations, warehouse):
    outcome = import_query(sample_sql, D, sample_annotations, Spy(warehouse, tamper=True))
    assert outcome.results_match is False
    assert (IssueCode.ROUNDTRIP_RESULTS_DIFFER, Severity.ERROR) in _codes(outcome)
    assert outcome.definition.state is DefinitionState.DRAFT


def test_truncated_results_are_incomplete_not_passed(sample_sql, sample_annotations, warehouse):
    outcome = import_query(sample_sql, D, sample_annotations, Spy(warehouse, truncate=True))
    assert outcome.results_match is None
    assert _codes(outcome) == [(IssueCode.CHECKS_INCOMPLETE, Severity.WARNING)]
    assert outcome.definition.state is DefinitionState.DRAFT


def test_error_issue_keeps_draft_even_when_results_match(warehouse):
    sql = "SELECT deal_id FROM deals WHERE NOT (closed_at >= '2026-01-01')"
    annotations = AnnotationFile(
        id="x",
        title="x",
        variables=[
            Annotation(
                name="since", type=VariableType.DATE, role=Role.CHANGEABLE, literals=["main.L1"]
            )
        ],
    )
    outcome = import_query(sql, D, annotations, warehouse)
    assert outcome.results_match is True
    assert _codes(outcome) == [(IssueCode.DESCRIPTION_REQUIRED, Severity.ERROR)]
    assert outcome.definition.state is DefinitionState.DRAFT


def test_multi_place_example_imports_and_runs(collections_sql, collections_annotations, warehouse):
    outcome = import_query(collections_sql, D, collections_annotations, warehouse)
    assert outcome.issues == []
    assert outcome.results_match is True
    assert outcome.definition.state is DefinitionState.LLM_ANNOTATED
    assert outcome.definition.variable("min_booked").unit == "thousand USD"
    run = render_definition(
        outcome.definition,
        {"period": {"start": "2025-10-01", "end": "2026-01-01"}, "min_booked": 1000.75},
        warehouse=warehouse,
        run=True,
    )
    assert run.result is not None and run.result.columns == ["region", "booked", "collected"]
    assert run.result.rows and all(row[1] >= 1_000_750 for row in run.result.rows)


def test_example_definition_files_match_a_fresh_import(
    sample_sql, sample_annotations, collections_sql, collections_annotations, warehouse
):
    """examples/definitions/*.yml are regenerated by `cteforge import`; keep them current."""
    for name, sql, annotations in (
        ("realization_rate", sample_sql, sample_annotations),
        ("booked_vs_collected", collections_sql, collections_annotations),
    ):
        fresh = import_query(sql, D, annotations, warehouse).definition
        assert load_definition(EXAMPLES / "definitions" / f"{name}.yml") == fresh, name
