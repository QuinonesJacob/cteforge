import { useState } from "react";
import { createToken, listTokens, revokeToken } from "../api/endpoints";
import { getToken } from "../api/token";
import type { CreateTokenRequest, NewToken, TokenCard, ToolInfo, User } from "../api/types";
import { canMintOwnToken } from "../lib/roles";
import { useToast } from "../state/ToastContext";
import { useAsync } from "../state/useAsync";
import { ErrorState } from "./ErrorState";
import { Loading } from "./Loading";
import { TokenForm } from "./TokenForm";
import { TokenList } from "./TokenList";
import { TokenReveal } from "./TokenReveal";

/**
 * Settings → My tokens (ADR 0027): the signed-in user's personal access tokens. Generate one
 * (shown once, with copy), see name / prefix / last use / expiry, revoke. The checklist offers
 * only what the role allows (`role_allowed` from /me). Agents never get a generate button.
 */
export function MyTokensCard({ user, catalog }: { user: User; catalog: ToolInfo[] | null | undefined }) {
  const toast = useToast();
  const tokens = useAsync((signal) => listTokens(undefined, { signal }), []);
  const [creating, setCreating] = useState(false);
  const [busy, setBusy] = useState<string | null>(null);
  const [revealed, setRevealed] = useState<NewToken | null>(null);
  const [formKey, setFormKey] = useState(0);
  const current = getToken()?.slice(0, 12) ?? null;

  async function create(body: CreateTokenRequest) {
    setBusy("create");
    try {
      const made = await createToken(body);
      setRevealed(made);
      setCreating(false);
      setFormKey((k) => k + 1);
      tokens.reload();
    } catch (err) {
      toast.error(err, "Could not generate the token");
    } finally {
      setBusy(null);
    }
  }

  async function revoke(token: TokenCard) {
    const self = Boolean(current && token.prefix === current);
    const warning = self ? " You are signed in with it: you will be signed out." : "";
    if (!window.confirm(`Revoke the token "${token.name}"? It stops working on its next call.${warning}`)) return;
    setBusy(token.id);
    try {
      await revokeToken(token.id);
      toast.success(`Token "${token.name}" revoked`);
      tokens.reload();
    } catch (err) {
      toast.error(err, "Could not revoke the token");
    } finally {
      setBusy(null);
    }
  }

  const mayMint = canMintOwnToken(user);
  return (
    <section className="card" aria-labelledby="my-tokens-title">
      <div className="section-head">
        <h2 id="my-tokens-title">My tokens</h2>
        {mayMint && !creating && (
          <button type="button" className="btn btn-sm btn-primary" onClick={() => setCreating(true)}>
            Generate token
          </button>
        )}
      </div>
      <p className="muted small">
        Personal access tokens sign in the GUI, the HTTP API and MCP clients (Claude Code, Cursor, CI). Each has its own
        tools within your role ({user.role}).
        {!mayMint && " Tokens for agent users are generated by a person."}
      </p>
      {revealed && (
        <TokenReveal
          name={revealed.info.user_name}
          tokenName={revealed.info.name}
          token={revealed.token}
          onDismiss={() => setRevealed(null)}
        />
      )}
      {creating && mayMint && (
        <TokenForm
          key={formKey}
          idPrefix="my-token"
          catalog={catalog}
          allowed={user.role_allowed ?? user.tools ?? []}
          defaults={user.role_defaults ?? user.tools ?? []}
          busy={busy === "create"}
          onSubmit={(b) => void create(b)}
          onCancel={() => setCreating(false)}
        />
      )}
      {tokens.loading && !tokens.data ? (
        <Loading />
      ) : tokens.error ? (
        <ErrorState error={tokens.error} onRetry={tokens.reload} />
      ) : (
        <TokenList
          label="My token list"
          tokens={tokens.data ?? []}
          busy={busy}
          currentPrefix={current}
          onRevoke={(t) => void revoke(t)}
        />
      )}
    </section>
  );
}
